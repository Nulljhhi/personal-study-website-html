  function escapeHtml(text) {
    return text
      .replace(/&/g, "&amp;")
      .replace(/</g, "&lt;")
      .replace(/>/g, "&gt;");
  }

  function renderInline(text) {
    var html = escapeHtml(text);
    html = html.replace(/\*\*([^*]+)\*\*/g, "<strong>$1</strong>");
    html = html.replace(/(^|[^*\w])\*([^*\s][^*]*)\*(?![*\w])/g, "$1<em>$2</em>");
    html = html.replace(/`([^`]+)`/g, "<code>$1</code>");
    return html;
  }

  /* Tiny markdown renderer for the documentation content above
     (headings, bullet and numbered lists, pipe tables, fenced code, bold,
     italics, code spans). */
  function renderMarkdown(md) {
    var lines = md.split("\n");
    var html = [];
    var paragraph = [];
    var listItems = [];
    var listTag = "ul";
    var tableRows = [];
    var codeLines = null;

    function flushParagraph() {
      if (paragraph.length) {
        html.push("<p>" + renderInline(paragraph.join(" ")) + "</p>");
        paragraph = [];
      }
    }
    function flushList() {
      if (listItems.length) {
        var items = "";
        for (var i = 0; i < listItems.length; i++) {
          items += "<li>" + renderInline(listItems[i]) + "</li>";
        }
        html.push("<" + listTag + ">" + items + "</" + listTag + ">");
        listItems = [];
      }
    }
    function flushTable() {
      if (!tableRows.length) return;
      var rows = [];
      for (var i = 0; i < tableRows.length; i++) {
        var cells = tableRows[i].split("|").slice(1, -1);
        for (var c = 0; c < cells.length; c++) cells[c] = cells[c].trim();
        rows.push(cells);
      }
      var separatorIndex = -1;
      for (var r = 1; r < rows.length; r++) {
        var allDashes = rows[r].length > 0;
        for (var d = 0; d < rows[r].length; d++) {
          if (!/^:?-{3,}:?$/.test(rows[r][d])) allDashes = false;
        }
        if (allDashes) { separatorIndex = r; break; }
      }
      var table = "<table>";
      if (separatorIndex > 0) {
        table += "<thead><tr>";
        for (var h = 0; h < rows[0].length; h++) {
          table += "<th>" + renderInline(rows[0][h]) + "</th>";
        }
        table += "</tr></thead><tbody>";
        for (var b = separatorIndex + 1; b < rows.length; b++) {
          table += "<tr>";
          for (var bb = 0; bb < rows[b].length; bb++) {
            table += "<td>" + renderInline(rows[b][bb]) + "</td>";
          }
          table += "</tr>";
        }
        table += "</tbody>";
      } else {
        table += "<tbody>";
        for (var t = 0; t < rows.length; t++) {
          table += "<tr>";
          for (var tt = 0; tt < rows[t].length; tt++) {
            table += "<td>" + renderInline(rows[t][tt]) + "</td>";
          }
          table += "</tr>";
        }
        table += "</tbody>";
      }
      table += "</table>";
      html.push(table);
      tableRows = [];
    }

    for (var i = 0; i < lines.length; i++) {
      var line = lines[i];
      if (codeLines !== null) {
        if (/^```/.test(line.trim())) {
          html.push("<pre>" + escapeHtml(codeLines.join("\n")) + "</pre>");
          codeLines = null;
        } else {
          codeLines.push(line);
        }
        continue;
      }
      var trimmed = line.trim();
      if (trimmed === "") {
        flushParagraph();
        flushList();
        flushTable();
        continue;
      }
      if (/^```/.test(trimmed)) {
        flushParagraph();
        flushList();
        flushTable();
        codeLines = [];
        continue;
      }
      if (trimmed.charAt(0) === "|") {
        flushParagraph();
        flushList();
        tableRows.push(trimmed);
        continue;
      }
      flushTable();
      if (/^###\s/.test(trimmed)) { flushParagraph(); flushList(); html.push("<h3>" + renderInline(trimmed.slice(4)) + "</h3>"); continue; }
      if (/^##\s/.test(trimmed)) { flushParagraph(); flushList(); html.push("<h2>" + renderInline(trimmed.slice(3)) + "</h2>"); continue; }
      if (/^#\s/.test(trimmed)) { flushParagraph(); flushList(); html.push("<h1>" + renderInline(trimmed.slice(2)) + "</h1>"); continue; }
      if (/^-\s/.test(trimmed)) {
        flushParagraph();
        if (listTag !== "ul") flushList();
        listTag = "ul";
        listItems.push(trimmed.slice(2));
        continue;
      }
      var numbered = /^\d+\.\s+/.exec(trimmed);
      if (numbered) {
        flushParagraph();
        if (listTag !== "ol") flushList();
        listTag = "ol";
        listItems.push(trimmed.slice(numbered[0].length));
        continue;
      }
      flushList();
      paragraph.push(trimmed);
    }
    flushParagraph();
    flushList();
    flushTable();
    if (codeLines !== null) {
      html.push("<pre>" + escapeHtml(codeLines.join("\n")) + "</pre>");
    }
    return html.join("\n");
  }

